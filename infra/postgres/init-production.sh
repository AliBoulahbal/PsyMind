#!/bin/sh
set -eu
export PGPASSWORD="$POSTGRES_OWNER_PASSWORD"

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_OWNER" --dbname "$POSTGRES_DB" <<SQL
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${POSTGRES_APP}') THEN
    CREATE ROLE ${POSTGRES_APP} LOGIN PASSWORD '${POSTGRES_APP_PASSWORD}'
      NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
  END IF;
END
\$\$;

GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO ${POSTGRES_APP};
GRANT USAGE ON SCHEMA public TO ${POSTGRES_APP};
ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_OWNER} IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${POSTGRES_APP};
ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_OWNER} IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO ${POSTGRES_APP};
SQL
